/* Feature-matrix generator — dumps every catalog feature -> endpoint ->
 * workflow -> node classes -> models -> cloud-manifest row -> license, plus
 * lint/test coverage, to a markdown report. Read-only; offline.
 *
 *   pnpm tsx scripts/feature-matrix.ts
 */
import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const REPORTS = process.env.OF_REPORTS ?? path.resolve(ROOT, "../of-reports");

type AnyRec = Record<string, any>;

const FILE_TOKEN = /[A-Za-z0-9_./-]+\.(safetensors|pt|pth|onnx|bin|gguf|json|ckpt|npz)\b/g;

async function main() {
  const { ALL_MODELS: MODELS = [] } = await import("../src/lib/catalog/video-models.ts" as any);
  const gen = await import("../src/lib/catalog/licenses.generated.ts" as any);
  const WORKFLOW_LICENSES: Record<string, { class: string; components: any[] }> = gen.WORKFLOW_LICENSES ?? {};
  const ENDPOINT_GRAPHS: Record<string, string> = gen.ENDPOINT_GRAPHS ?? {};
  const { RECIPE_LICENSES = {} } = await import("../src/lib/catalog/licenses.ts" as any) as { RECIPE_LICENSES: Record<string, { class: string; components: any[] }> };

  const cloud = JSON.parse(fs.readFileSync(path.join(ROOT, "scripts/runpod/models.cloud.json"), "utf8"));
  const cloudByName = new Map<string, AnyRec>();
  for (const e of cloud.models as AnyRec[]) {
    cloudByName.set(e.name, e);
    if (e.path) cloudByName.set(e.path, e);
    if (e.target && e.name) cloudByName.set(`${e.target}/${e.name}`, e);
  }
  const cloudEntries = cloud.models as AnyRec[];

  const schemas = JSON.parse(fs.readFileSync(path.join(ROOT, "tests/fixtures/node-schemas.json"), "utf8"));
  const schemaNodes: Record<string, AnyRec> = schemas.nodes ?? {};

  // recipe name -> step workflow files: direct `workflow:` refs plus
  // findEndpoint("motionfield/...") refs resolved through ENDPOINT_GRAPHS
  const recipeDir = path.join(ROOT, "src/lib/generation/recipes");
  const recipeSteps = new Map<string, string[]>();
  for (const f of fs.readdirSync(recipeDir).filter((f) => f.endsWith(".ts"))) {
    const src = fs.readFileSync(path.join(recipeDir, f), "utf8");
    const files = new Set<string>([...src.matchAll(/workflow:\s*"([^"]+\.json)"/g)].map((m) => m[1]));
    for (const m of src.matchAll(/findEndpoint\(\s*"([^"]+)"\s*\)/g)) {
      const wf = ENDPOINT_GRAPHS[m[1]];
      if (wf) files.add(wf);
    }
    recipeSteps.set(f.replace(/\.ts$/, ""), [...files]);
  }

  // unit-test coverage
  const testFiles = fs.readdirSync(path.join(ROOT, "tests/unit")).filter((f) => f.endsWith(".test.ts"));
  const testSrc = new Map<string, string>();
  for (const f of testFiles) testSrc.set(f, fs.readFileSync(path.join(ROOT, "tests/unit", f), "utf8"));
  const snap = fs.existsSync(path.join(ROOT, "tests/fixtures/catalog-snapshot.json"))
    ? fs.readFileSync(path.join(ROOT, "tests/fixtures/catalog-snapshot.json"), "utf8") : "";
  function testsFor(...tokens: string[]): string[] {
    const out = new Set<string>();
    for (const [f, src] of testSrc) for (const t of tokens) if (t && src.includes(t)) out.add(f);
    return [...out];
  }

  function workflowNodes(file: string): string[] {
    const p = path.join(ROOT, "workflows", file);
    if (!fs.existsSync(p)) return [];
    const g = JSON.parse(fs.readFileSync(p, "utf8"));
    const cls = new Set<string>();
    for (const [k, n] of Object.entries(g)) {
      if (k !== "_meta" && n && typeof n === "object" && (n as AnyRec).class_type) cls.add((n as AnyRec).class_type);
    }
    return [...cls].sort();
  }

  // non-weight components: provenance label instead of a cloud row
  const NON_WEIGHT: [RegExp, string][] = [
    [/motionfield node pack/i, "repo pack — rsync'd by setup.sh"],
    [/voices_v1\.bin|kokoro-82m voices/i, "generated by setup.sh (pack np.savez)"],
    [/ffmpeg/i, "user's system binary — not shipped"],
    [/whisper\.cpp \(whisper-cli\)/i, "built by setup.sh"],
    [/three\.js|opentype\.js/i, "npm dependency"],
    [/space grotesk/i, "repo asset"],
    [/translation — your own local llm/i, "user-provided local LLM"],
    [/game-build recipe/i, "recipe not implemented — no endpoint exposes it"],
    [/in-repo /i, "repo code — no download"],
    [/playwright chromium/i, "npm/browser dep — installed by setup"],
  ];

  // resolve a license component name to cloud-manifest rows (inner filenames,
  // glob prefixes like trellis_2_*, target-path slugs like sd-vae-ft-mse)
  function cloudRows(name: string): { label: string; e?: AnyRec; provenance?: string }[] {
    const direct = cloudByName.get(name);
    if (direct) return [{ label: name, e: direct }];
    for (const [re, prov] of NON_WEIGHT) if (re.test(name)) return [{ label: name, provenance: prov }];
    const tokens = [...new Set((name.match(FILE_TOKEN) ?? []).map((t) => t.split("/").pop()!))];
    if (name.includes("*")) {
      const globTok = (name.match(/[A-Za-z0-9_.-]+\*/) ?? [""])[0].replace(/\*+$/, "");
      if (globTok) {
        const hits = cloudEntries.filter((e) => e.name.startsWith(globTok) || (e.target ?? "").includes(globTok));
        if (hits.length) return hits.map((e) => ({ label: e.name, e }));
      }
    }
    if (tokens.length) return tokens.map((t) => ({ label: t, e: cloudByName.get(t) }));
    // slug match on the cloud target path (e.g. "sd-vae-ft-mse", "chatterbox")
    const slug = [...name.matchAll(/[a-z0-9][a-z0-9_-]{4,}/gi)]
      .map((m) => m[0].toLowerCase())
      .filter((s) => !["pack", "weights", "model", "bundled", "checkpoint"].includes(s))
      .find((s) => cloudEntries.some((e) => (e.target ?? "").includes(s)));
    if (slug) {
      const hits = cloudEntries.filter((e) => (e.target ?? "").includes(slug));
      if (hits.length) return hits.map((e) => ({ label: `${slug} → ${e.name}`, e }));
    }
    return [{ label: name }];
  }

  interface Row {
    feature: string; tool: string; endpoint: string; workflow: string;
    recipe?: string; classes: string[]; externalClasses: string[];
    models: { name: string; lic: string; cls: string; url: string; files: { label: string; tier: string; target: string; sha: string; provenance?: string }[] }[];
    licClass: string; tests: string[]; snap: boolean;
  }

  const rows: Row[] = [];
  const seen = new Set<string>();

  for (const m of MODELS as AnyRec[]) {
    for (const w of m.workflows ?? []) {
      const ep: string = w.endpointId;
      const recipeName: string | undefined = w.providers?.recipe?.name;
      const wfFiles: string[] = recipeName
        ? (recipeSteps.get(recipeName) ?? [])
        : [ENDPOINT_GRAPHS[ep] ?? w.providers?.comfy?.workflow].filter(Boolean);
      const allClasses = new Set<string>();
      const allComps = new Map<string, AnyRec>();
      let worst = "open";
      const rank: Record<string, number> = { open: 0, "permissive-terms": 1, restricted: 2, "banned-known": 3 };
      for (const f of wfFiles) {
        for (const c of workflowNodes(f)) allClasses.add(c);
        const lic = WORKFLOW_LICENSES[f];
        if (lic && (rank[lic.class] ?? 0) > (rank[worst] ?? 0)) worst = lic.class;
        for (const c of lic?.components ?? []) allComps.set(c.name, c);
      }
      const recLic = recipeName ? RECIPE_LICENSES[recipeName] : undefined;
      if (recLic) {
        if ((rank[recLic.class] ?? 0) > (rank[worst] ?? 0)) worst = recLic.class;
        for (const c of recLic.components ?? []) allComps.set(c.name, c);
      }
      const external = [...allClasses].filter((c) => (schemaNodes[c]?.src ?? "").startsWith("pack:"));
      const comps = [...allComps.values()].map((c: AnyRec) => ({
        name: c.name, lic: c.license, cls: c.class, url: c.url,
        files: cloudRows(c.name).map((r) => ({
          label: r.label,
          tier: r.e?.tier ?? "—",
          target: r.provenance ?? r.e?.target ?? (r.e ? "?" : "not-in-cloud"),
          sha: r.e ? (String(r.e.sha256).length === 64 ? "ok" : "PENDING") : "—",
          provenance: r.provenance,
        })),
      }));
      const attached = w.license;
      if (attached?.components?.length && !comps.length) {
        for (const c of attached.components) allComps.set(c.name, c);
      }
      rows.push({
        feature: `${m.label} (${m.id})`, tool: w.label, endpoint: ep,
        workflow: recipeName
          ? (wfFiles.length ? `recipe:${recipeName} → ${wfFiles.join(", ")}` : `recipe:${recipeName} — local ffmpeg/three.js, no ComfyUI graph`)
          : (wfFiles[0] ?? "?"),
        recipe: recipeName,
        classes: [...allClasses].sort(), externalClasses: external,
        models: comps.length ? comps : [...allComps.values()].map((c: AnyRec) => ({
          name: c.name, lic: c.license, cls: c.class, url: c.url,
          files: cloudRows(c.name).map((r) => ({
            label: r.label, tier: r.e?.tier ?? "—",
            target: r.provenance ?? r.e?.target ?? "not-in-cloud",
            sha: r.e ? (String(r.e.sha256).length === 64 ? "ok" : "PENDING") : "—",
            provenance: r.provenance,
          })),
        })),
        licClass: attached?.class ?? ((wfFiles.length || recLic) ? worst : "?"),
        tests: testsFor(ep, ...wfFiles),
        snap: snap.includes(ep),
      });
      seen.add(ep);
    }
  }

  const orphans = Object.keys(ENDPOINT_GRAPHS).filter((e) => !seen.has(e));

  const out: string[] = [];
  out.push("# MotionField feature matrix — PHASE A2 (offline)", "");
  out.push(`Generated: ${new Date().toISOString().slice(0, 10)} · ${rows.length} catalog tools · ${orphans.length} orphan endpoint graphs`);
  out.push("");
  out.push("Route for every endpoint: `POST /api/jobs` with `endpoint_id`. Gates: `scripts/validate-workflow-schema.py` (72 workflows, 0 errors vs pinned schemas), `scripts/lint-workflows.py` (0 errors). `ws3-catalog-snapshot` covers every endpoint's serialized surface; `sha:PENDING` = gated sha resolves via fill-hashes.py + HF_TOKEN at setup time.");
  out.push("");
  let gaps = 0;
  for (const r of rows) {
    out.push(`## ${r.feature} — ${r.tool}`);
    out.push(`- endpoint: \`${r.endpoint}\` → \`${r.workflow}\` (license: **${r.licClass}**)`);
    out.push(`- node classes (${r.classes.length}): ${r.classes.join(", ") || "—"}`);
    out.push(`- external pack classes: ${r.externalClasses.length ? r.externalClasses.join(", ") : "none (core only)"}`);
    const cov = [...r.tests]; if (r.snap) cov.push("catalog-snapshot");
    out.push(`- unit tests: ${cov.length ? cov.join(", ") : "**none**"}`);
    if (r.models.length) {
      out.push(`- models:`);
      for (const m of r.models) {
        for (const f of m.files) {
          const flag = f.target === "not-in-cloud" ? " **GAP**" : "";
          out.push(`  - \`${m.name}\` — ${m.lic} (${m.cls})${m.files.length > 1 ? ` · file \`${f.label}\`` : ""} · tier ${f.tier} → \`${f.target}\` · sha:${f.sha}${flag} · ${m.url}`);
        }
      }
    } else {
      out.push(`- models: none declared`);
    }
    out.push("");
  }
  if (orphans.length) {
    out.push("## Orphan endpoint graphs (not surfaced in catalog MODELS)");
    for (const o of orphans) out.push(`- \`${o}\` → \`${ENDPOINT_GRAPHS[o]}\``);
    out.push("");
  }
  fs.mkdirSync(REPORTS, { recursive: true });
  const dest = path.join(REPORTS, "feature-matrix.md");
  fs.writeFileSync(dest, out.join("\n"));
  console.log(`wrote ${dest}: ${rows.length} tools, ${orphans.length} orphans`);
}

main();
