"""DA3 multiview geometry → the trajectory pose schema (re-shoot).

ComfyUI core's DA3Inference returns a DA3_GEOMETRY dict — consumed here at
runtime only (core is GPL-3.0; nothing of it is vendored into this MIT pack):

    depth      (S,H,W) f32   — raw model depth at the SOURCE image size
    image      (S,H,W,3) f32 — the input frames in [0,1]
    mode       "multiview"
    extrinsics (1,S,3,4) f32 — world-to-camera [R|t], OpenCV convention
                               (x right, y DOWN, z forward)
    intrinsics (1,S,3,3) f32 — pixel-space K for the PROCESSING dims
                               (centre principal point; fov-derived fx,fy)
    confidence (S,H,W) f32   — Small/Base only

Our pose frame (camera_splat/trajectory): metres, +x right, +y up, +z forward;
the OpenCV→ours change of basis is flip·R·flip (both cam AND world y flip —
a proper rotation, not the reflection a one-sided flip would be). Camera
centre c = -flip·Rᵀt. fov = horizontal degrees from K's fx.

DA3's world scale is relative, so depth AND camera centres are multiplied by
one factor: s = distance / median(centre 20% of frame-0 depth). The composed
trajectory's metre translations then land in the same frame the depth lives
in — one consistent scale end to end.
"""
import math
import os
import re
import tempfile

import numpy as np

from . import camera_splat as splat

DEG = math.pi / 180.0

# ------------------------------------------------------------- disk cache
# OF_DA3Windowed's windowed pass costs minutes per clip. Its cache CANNOT
# live in ComfyUI's temp dir — main.py wipes temp on every startup and the
# other lanes restart Comfy often — so it roots at ~/.motionfield/cache/da3.
# MOTIONFIELD_CACHE_DIR overrides the root (tests point it at a tmp dir);
# MOTIONFIELD_CACHE_CAP_BYTES overrides the 4 GiB LRU cap.

_CACHE_CAP_DEFAULT = 4 << 30


def _cache_root():
    root = os.environ.get("MOTIONFIELD_CACHE_DIR") or os.path.join(
        os.path.expanduser("~"), ".motionfield", "cache")
    return os.path.join(root, "da3")


def da3_cache_dir():
    path = _cache_root()
    os.makedirs(path, exist_ok=True)
    return path


def _safe_key(key):
    """Filename component for a cache entry — the key carries the clip
    content hash and the window params, but a hostile key must never
    resolve outside the cache dir: keep [A-Za-z0-9_.-] only and strip
    leading dots so no dotfile or ".." remnant survives."""
    safe = re.sub(r"[^A-Za-z0-9_.-]+", "_", str(key)).strip("._")
    return safe or "x"


def da3_cache_path(key):
    """Absolute path of key's npz — always inside da3_cache_dir()."""
    return os.path.join(da3_cache_dir(), f"of_da3win_{_safe_key(key)}.npz")


def da3_cache_get(key):
    """Cached npz → {name: array}, or None on a miss or a corrupt file. A
    corrupt/unreadable entry is unlinked — it can only be regenerated by a
    full pass, and a poisoned file must not crash the node."""
    path = da3_cache_path(key)
    try:
        with np.load(path, allow_pickle=False) as z:
            out = {k: z[k] for k in z.files}
    except Exception:
        try:
            os.remove(path)
        except OSError:
            pass
        return None
    try:
        os.utime(path)          # the LRU clock is mtime
    except OSError:
        pass
    return out


def _cap_bytes(cap_bytes):
    if cap_bytes is not None:
        return int(cap_bytes)
    env = os.environ.get("MOTIONFIELD_CACHE_CAP_BYTES")
    try:
        return int(env) if env else _CACHE_CAP_DEFAULT
    except ValueError:
        return _CACHE_CAP_DEFAULT


def da3_cache_put(key, arrays, cap_bytes=None):
    """Write arrays to key's npz (tmp file + rename so a crash can't leave
    a half-written entry), then evict least-recently-used entries until
    the directory fits the cap. The new entry lands even if it alone
    exceeds the cap — the cap bounds the cache, not the clip."""
    path = da3_cache_path(key)
    fd, tmp = tempfile.mkstemp(prefix=".of_", suffix=".tmp",
                               dir=os.path.dirname(path))
    try:
        with os.fdopen(fd, "wb") as f:
            np.savez_compressed(f, **arrays)
        os.replace(tmp, path)
    except BaseException:
        try:
            os.remove(tmp)
        except OSError:
            pass
        raise
    _cache_evict(_cap_bytes(cap_bytes), protect=path)


def _cache_evict(cap_bytes, protect=None):
    try:
        ents = [e for e in os.scandir(da3_cache_dir())
                if e.name.endswith(".npz") and e.is_file()]
    except OSError:
        return
    aged, total = [], 0
    for e in ents:
        try:
            st = e.stat()
        except OSError:
            continue
        aged.append((st.st_mtime, st.st_size, e.path))
        total += st.st_size
    for _mtime, size, path in sorted(aged):
        if total <= cap_bytes:
            break
        if protect is not None and os.path.realpath(path) == os.path.realpath(protect):
            continue                    # the just-written entry always lands
        try:
            os.remove(path)
            total -= size
        except OSError:
            pass


def basis_to_pose(right, up, fwd, pos, t, fov):
    """Basis vectors (camera axes in world coords) → our pose dict. Inverse
    of camera_splat.rotation(): fwd = [sin yaw·cos p, sin p, cos yaw·cos p]."""
    pitch = math.asin(max(-1.0, min(1.0, float(fwd[1]))))
    yaw = math.atan2(float(fwd[0]), float(fwd[2]))
    cp = math.cos(pitch)
    roll = math.atan2(float(right[1]), float(up[1])) if abs(cp) > 1e-6 else 0.0
    return {
        "t": float(t),
        "pos": [float(x) for x in pos],
        "yaw": ((yaw / DEG + 180.0) % 360.0) - 180.0,
        "pitch": pitch / DEG,
        "roll": roll / DEG,
        "fov": float(fov),
    }


def _as_numpy(x):
    """torch tensor or ndarray → float64 ndarray (the dict arrives CPU-side)."""
    if hasattr(x, "detach"):
        x = x.detach().cpu().numpy()
    return np.asarray(x, dtype=np.float64)


def _centre_scale(depth0, distance):
    """s = distance / median(centre 20% band of frame-0 depth)."""
    h, w = depth0.shape
    band = depth0[int(0.4 * h):max(int(0.6 * h), int(0.4 * h) + 1),
                  int(0.4 * w):max(int(0.6 * w), int(0.4 * w) + 1)]
    band = band[np.isfinite(band) & (band > 1e-9)]
    med = float(np.median(band)) if band.size else 0.0
    return float(distance) / med if med > 1e-9 else 1.0


def geometry_to_poses(geometry, fps, distance, process_res=504,
                      resize_method="upper_bound_resize", min_confidence=0.0):
    """DA3_GEOMETRY → (poses, depth_m, n_frames).

    poses[t] is the SOURCE camera's pose at frame t in our schema — the
    anchor a new trajectory replaces. depth_m is (S,H,W) metres, scaled to
    the same frame as the pose positions. Pixels whose DA3 confidence falls
    under min_confidence get depth +inf — they splat nowhere and surface as
    holes for the fill pass instead of smearing wrong geometry.

    process_res/resize_method ride the node contract — the recovered K
    carries the processing dims itself, so the fov reads the width straight
    off it (2·K[0,2]) rather than re-deriving what DA3 resized to.
    """
    ext_raw = geometry.get("extrinsics")
    intr_raw = geometry.get("intrinsics")
    if ext_raw is None or intr_raw is None:
        raise ValueError("da3_geometry carries no extrinsics/intrinsics — run DA3Inference in multiview mode")
    ext = _as_numpy(ext_raw)
    intr = _as_numpy(intr_raw)
    depth = _as_numpy(geometry["depth"])
    img = _as_numpy(geometry["image"])
    if ext.ndim == 4:
        ext = ext[0]                      # (S,3,4)
    if intr.ndim == 4:
        intr = intr[0]                    # (S,3,3)
    n = int(img.shape[0])

    s = _centre_scale(depth[0], distance)
    depth_m = depth * s
    conf = geometry.get("confidence")
    if min_confidence > 0 and conf is not None:
        conf = _as_numpy(conf)
        depth_m = np.where(conf >= min_confidence, depth_m, np.inf)

    poses = []
    flip = np.diag([1.0, -1.0, 1.0])
    for i in range(min(n, ext.shape[0])):
        w2c = ext[i]
        R, tvec = w2c[:, :3], w2c[:, 3]
        # OpenCV (cam y-down, world y-down) → ours (cam y-up, world y-up) is a
        # change of basis on BOTH sides: flip·R·flip — a proper rotation. A
        # left-only flip·R is a reflection (det −1): basis_to_pose reads it as
        # roll≈180 and the reprojection conjugates the source's move instead
        # of cancelling it (the pan doubles on screen rather than freezing).
        pos = -(flip @ R.T @ tvec) * s
        rows = flip @ R @ flip
        fx = float(intr[i][0, 0])
        cx = float(intr[i][0, 2])
        # K is pixel-space at the processing dims with a centre principal
        # point — the processing width is 2·cx, so fov = 2·atan(cx/fx). An
        # identity-ish K (fx ≈ 1 px) is DA3's "no camera head" fallback; a
        # fov derived from it would silently lie, so it errors instead.
        if not (math.isfinite(fx) and math.isfinite(cx)) or fx <= 1.0 + 1e-6:
            raise ValueError(
                "da3_geometry intrinsics are the identity fallback (fx≈1) — "
                "no camera head; run DA3Inference with a pose method that emits K")
        fov = 2.0 * math.atan(cx / fx) / DEG
        poses.append(basis_to_pose(rows[0], rows[1], rows[2], pos, i / fps, fov))
    return poses, depth_m.astype(np.float32), n


def anchor_frames(frames, anchor):
    """Rigidly re-anchor a composed pose stream so frame 0 IS `anchor` —
    the new path starts exactly where the source camera started, then
    diverges. With B = basis rows (camera axes in world, row-vector
    convention: cam→world is q·B), the rigid map composed[0]→anchor is
    Q = B_0ᵀ·B_a applied on the right:

        pos' = a.pos + (pos − pos0)·Q      B' = B·Q

    so B'_0 = B_a and pos'_0 = a.pos. The source camera's own move never
    enters — the stack replaces it. fov scales by anchor.fov/frame0.fov:
    a zoom move still zooms, and the source's own lens is kept otherwise.
    `anchor` is a pose dict or a pose list (its [0] is used)."""
    if isinstance(anchor, list):
        if not anchor:
            raise ValueError("anchor pose list is empty")
        anchor = anchor[0]
    f0 = frames[0]
    B_a = np.stack(splat.rotation(anchor))   # rows: a's axes in world
    B_0 = np.stack(splat.rotation(f0))
    Q = B_0.T @ B_a
    p0 = np.asarray(f0["pos"], dtype=np.float64)
    pa = np.asarray(anchor["pos"], dtype=np.float64)
    fov_scale = float(anchor.get("fov", f0["fov"])) / float(f0["fov"] or 1.0)

    out = []
    for f in frames:
        B = np.stack(splat.rotation(f))
        Bn = B @ Q
        pos = pa + (np.asarray(f["pos"], dtype=np.float64) - p0) @ Q
        nf = dict(f)
        nf["pos"] = [float(x) for x in pos]
        nf["fov"] = float(f["fov"]) * fov_scale
        p = basis_to_pose(Bn[0], Bn[1], Bn[2], pos, f["t"], nf["fov"])
        nf.update({k: p[k] for k in ("yaw", "pitch", "roll")})
        if "focus" in f:
            nf["focus"] = f["focus"]
        out.append(nf)
    return out


def window_starts(n, window, overlap):
    """Cover [0,n) with `window`-long views stepping `window-overlap`."""
    window = max(2, int(window)); overlap = max(0, int(overlap))
    if overlap >= window:
        overlap = window - 1
    if n <= window:
        return [0]
    step = window - overlap
    starts = list(range(0, n - window + 1, step))
    if starts[-1] + window < n:
        starts.append(n - window)
    return starts


def _shared_depth_scale(depth_s, d_cnt, geo, shared_g, shared_l):
    """Scale of this window's world vs the global one, from the shared
    views' depth medians — a view is the same physical camera in both
    windows, so its depth map differs only by the world scale factor."""
    rs = []
    for g, s in zip(shared_g, shared_l):
        a = depth_s[g] / max(d_cnt[g], 1)
        b = geo["depth"][s]
        m = np.isfinite(a) & np.isfinite(b) & (a > 0) & (b > 0)
        if m.sum() >= 64:
            mb = float(np.median(b[m]))
            if mb > 0:
                rs.append(float(np.median(a[m])) / mb)
    if not rs:
        return None
    s = float(np.median(rs))
    return s if np.isfinite(s) and s > 0 else None


def _sim_from_shared(prev_ext, cur_ext, shared_prev, shared_cur, s):
    """Similarity (R,t) mapping window-local world → global world. The w2c
    delta between the same view's two estimates is rigid for ANY camera
    path (scale lives in the translations and depths, not the rotation):
    R_a = R_gᵀR_l, t_a = R_gᵀ(s·t_l − t_g). Fits on camera CENTRES instead
    degenerate for a locked-off or pan-only source — the shared centres
    coincide and the Umeyama SVD returns a garbage scale that compounds
    per window."""
    Rs, ts = [], []
    for g, l in zip(shared_prev, shared_cur):
        R_g = prev_ext[g][:, :3]; t_g = prev_ext[g][:, 3]
        R_l = cur_ext[l][:, :3]; t_l = cur_ext[l][:, 3]
        Rs.append(R_g.T @ R_l)
        ts.append(R_g.T @ (s * t_l - t_g))
    Rm = np.mean(Rs, axis=0)
    U, _, Vt = np.linalg.svd(Rm)
    R_a = U @ np.diag([1.0, 1.0, np.sign(np.linalg.det(U @ Vt))]) @ Vt
    return R_a, np.median(ts, axis=0)


def stitch_windows(windows, n):
    """Chain windowed DA3 multiview results into one geometry dict.

    `windows` is a list of (start, geometry) where geometry carries numpy
    depth (w,H,W), image (w,H,W,3), extrinsics (w,3,4), intrinsics (w,3,3)
    and optional confidence (w,H,W). Each window's world frame is chained
    to the global one by the rigid w2c deltas of the shared views plus a
    scale read off their depth ratio — centre fits degenerate when the
    source camera barely translates. Overlapping depth/confidence
    averages; extrinsics keep the earliest window's estimate.
    """
    ext = np.zeros((n, 3, 4))
    K = np.zeros((n, 3, 3)); k_cnt = np.zeros(n)
    have = np.zeros(n, bool)
    depth_s = conf_s = img = None
    d_cnt = c_cnt = None
    for start, geo in windows:
        w = geo["depth"].shape[0]
        ge = geo["extrinsics"]
        # views already placed (earlier windows) that this one re-sees
        shared_g = [g for g in range(start, start + w) if have[g]]
        shared_l = [g - start for g in shared_g]
        if not have.any():
            s_a, R_a, t_a = 1.0, np.eye(3), np.zeros(3)
        elif shared_g:
            s_a = _shared_depth_scale(
                depth_s, d_cnt, geo, shared_g, shared_l)
            if s_a is None:
                s_a = 1.0     # depths unreadable — near-scale beats a guess
            R_a, t_a = _sim_from_shared(
                ext, ge, shared_g, shared_l, s_a)
        else:   # no shared view — extend the previous transform unchanged
            s_a, R_a, t_a = s_a, R_a, t_a
        if depth_s is None:
            h, wd = geo["depth"].shape[1:3]
            depth_s = np.zeros((n, h, wd)); d_cnt = np.zeros(n)
            if geo.get("confidence") is not None:
                conf_s = np.zeros((n, h, wd)); c_cnt = np.zeros(n)
            img = np.zeros((n,) + geo["image"].shape[1:])
        for s in range(w):
            g = start + s
            if not have[g]:
                R = ge[s][:, :3]; t = ge[s][:, 3]
                ext[g][:, :3] = R @ R_a.T
                ext[g][:, 3] = s_a * t - R @ R_a.T @ t_a
                img[g] = geo["image"][s]
                have[g] = True
            depth_s[g] += geo["depth"][s] * s_a; d_cnt[g] += 1
            K[g] += geo["intrinsics"][s]; k_cnt[g] += 1
            if conf_s is not None and geo.get("confidence") is not None:
                conf_s[g] += geo["confidence"][s]; c_cnt[g] += 1
    out = {"depth": depth_s / d_cnt[:, None, None],
           "image": img, "mode": "multiview",
           "extrinsics": ext[None], "intrinsics": (K / k_cnt[:, None, None])[None]}
    if conf_s is not None:
        out["confidence"] = conf_s / c_cnt[:, None, None]
    return out
