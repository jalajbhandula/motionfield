import { promises as fs } from "fs";
import os from "os";
import path from "path";
import { spawn } from "child_process";
import { and, eq } from "drizzle-orm";
import { z } from "zod";
import { getDb, schema } from "@/db";
import { filePathFor, saveBytes } from "@/lib/storage";
import { filesPathSchema, parseSceneSpec } from "@/lib/render/spec";
import type { RecipeCtx, RecipeFn } from "../recipe";
import type { ProviderOutputItem } from "../types";

/**
 * Motion render recipe - renders a stored SceneSpec to an MP4 through the
 * headless exporter (scripts/render/export.ts) against this app's own
 * /render/motion page, then saves it via storage.
 *
 * Input params (zod-checked):
 *   spec_id - uuid of a render_specs row owned by the job's user, or
 *   spec - an inline SceneSpec object (handy for direct calls/tests)
 *   values - optional { paramId: number } overrides applied via setParams
 *   source - optional "/files/…" video the job's user owns (their upload or
 *              a job output asset): the spec is rendered transparent and
 *              composited over it, audio carried through
 *
 * Exports are serialized through a module-level queue: one headless-Chromium +
 * ffmpeg pair at a time so parallel jobs don't fight over CPU/RAM.
 */

const valuesSchema = z.record(z.string(), z.number().finite());
const sourceSchema = filesPathSchema.describe('"/files/…" video owned by the job\'s user');
export const motionRenderParamsSchema = z.union([
  z.strictObject({ spec_id: z.uuid(), values: valuesSchema.optional(), source: sourceSchema.optional() }),
  z.strictObject({ spec: z.unknown(), values: valuesSchema.optional(), source: sourceSchema.optional() }),
]);

/** The job's user may only composite over their own files - an upload row or
 *  an asset row generated by one of their jobs. Anything else is an error,
 *  never a silent fallthrough to someone else's media. */
async function resolveOwnedSource(source: string, userId: string): Promise<string> {
  const db = await getDb();
  const [u] = await db.select({ id: schema.uploads.id }).from(schema.uploads)
    .where(and(eq(schema.uploads.url, source), eq(schema.uploads.userId, userId))).limit(1);
  let owned = Boolean(u);
  if (!owned) {
    const [a] = await db.select({ id: schema.assets.id }).from(schema.assets)
      .where(and(eq(schema.assets.url, source), eq(schema.assets.userId, userId))).limit(1);
    owned = Boolean(a);
  }
  if (!owned) throw new Error("source not found");
  const fp = filePathFor(source);
  if (!fp) throw new Error("source not found");
  await fs.access(fp).catch(() => { throw new Error("source not found"); });
  return fp;
}

/** globalThis so Next.js dev HMR doesn't fork the queue on module reload. */
const g = globalThis as { __ofMotionQueue?: Promise<unknown> };
function enqueue<T>(fn: () => Promise<T>): Promise<T> {
  const p = (g.__ofMotionQueue ?? Promise.resolve()).then(fn, fn);
  g.__ofMotionQueue = p.then(() => {}, () => {});
  return p;
}

function runExport(args: string[], ctx: RecipeCtx): Promise<void> {
  return new Promise((res, rej) => {
    // a job cancelled while it waited in the export queue must never spawn
    // the browser/ffmpeg pair - check the signal at the moment we'd start
    if (ctx.signal.aborted) return rej(ctx.signal.reason instanceof Error ? ctx.signal.reason : new Error("aborted"));
    const proc = spawn(process.execPath, args, { cwd: process.cwd() });
    let errTail = "";
    const onAbort = () => proc.kill("SIGTERM");
    ctx.signal.addEventListener("abort", onAbort, { once: true });
    proc.stdout.on("data", (d) => {
      const m = /frame (\d+)\/(\d+)/.exec(d.toString());
      if (m) ctx.progress(5 + Math.round((Number(m[1]) / Number(m[2])) * 85), "rendering");
    });
    proc.stderr.on("data", (d) => { errTail = (errTail + d).slice(-4000); });
    proc.on("close", (code) => {
      ctx.signal.removeEventListener("abort", onAbort);
      if (code === 0) res();
      else rej(new Error(`exporter exited ${code}${errTail ? `: ${errTail.trim()}` : ""}`));
    });
    proc.on("error", rej);
  });
}

export const motionRenderRecipe: RecipeFn = async (input, ctx) => {
  const parsed = motionRenderParamsSchema.safeParse(input.params);
  if (!parsed.success) {
    throw new Error(`motion-render params invalid: ${parsed.error.issues[0]?.message ?? "bad params"}`);
  }
  const p = parsed.data;

  const db = await getDb();
  const [job] = await db.select({ userId: schema.jobs.userId })
    .from(schema.jobs).where(eq(schema.jobs.id, input.jobId)).limit(1);
  if (!job) throw new Error("render spec not found");

  let spec: unknown;
  if ("spec_id" in p) {
    const [row] = await db.select().from(schema.renderSpecs)
      .where(eq(schema.renderSpecs.id, p.spec_id)).limit(1);
    // spec_id is only reachable through a job - and only the owner's own rows
    if (!row || row.userId !== job.userId) throw new Error("render spec not found");
    spec = row.spec;
  } else {
    spec = p.spec;
  }
  const sceneSpec = parseSceneSpec(spec); // zod error → readable job failure
  const values = p.values;
  // overlay mode: the "/files/…" source must resolve inside storage AND be
  // owned by the job's user (their upload or their own job's output asset)
  const sourcePath = p.source ? await resolveOwnedSource(p.source, job.userId) : null;

  ctx.progress(2, "queued for export");
  const dir = await fs.mkdtemp(path.join(os.tmpdir(), "of-render-"));
  try {
    const specFile = path.join(dir, "spec.json");
    const outFile = path.join(dir, "render.mp4");
    await fs.writeFile(specFile, JSON.stringify(sceneSpec));
    const args = [
      "--experimental-strip-types", "scripts/render/export.ts",
      "--spec", specFile, "--out", outFile, "--base", input.appBaseUrl,
    ];
    if (values) args.push("--params", JSON.stringify(values));
    if (sourcePath) args.push("--video", sourcePath);
    await enqueue(() => runExport(args, ctx));
    ctx.signal.throwIfAborted();

    ctx.progress(95, "saving");
    const data = await fs.readFile(outFile);
    const url = await saveBytes(`generated/${input.jobId}/motion.mp4`, data);
    ctx.progress(100, "done");
    return [{
      type: "video",
      url,
      width: sceneSpec.width,
      height: sceneSpec.height,
      duration: sceneSpec.duration,
    } satisfies ProviderOutputItem];
  } finally {
    await fs.rm(dir, { recursive: true, force: true }).catch(() => {});
  }
};
